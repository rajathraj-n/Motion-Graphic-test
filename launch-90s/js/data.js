const sumLines = ls => ls.reduce((n,l)=>n+l.qty*l.price,0);
function money(n){ return '$'+Math.round(n).toLocaleString('en-US'); }
function computeMetrics(subs, invoices){
  const revenue=invoices.reduce((n,i)=>n+sumLines(i.lines),0);
  const cost=subs.reduce((n,s)=>n+s.supplierQty*s.cost,0);
  const value=subs.filter(s=>s.status==='Active').reduce((n,s)=>n+s.qty*s.price,0);
  return {revenue,cost,value,profit:revenue-cost,margin:revenue?(revenue-cost)/revenue*100:0};
}
