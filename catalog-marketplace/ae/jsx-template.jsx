/*  RackNap Easy — Catalog & Marketplace (15 s, 3840x2160, 30 fps)
    After Effects build script.

    HOW TO USE
      1. Keep this file next to the "assets" folder.
      2. Install the fonts Inter + Inter Display (free, rsms.me/inter).
      3. After Effects > File > Scripts > Run Script File… > choose this file.
    The script builds a new project folder with three comps:
      • "RackNap Easy – Catalog & Marketplace 4K"  (main, edit headlines here)
      • "3D Scene – RackNap Catalog"               (2.5D camera move on the browser)
      • "Browser UI – Catalog & marketplace"      (real UI layers, cursor, card states)
    Generated by ae/build-jsx.js — edit timings there or directly in AE.
*/
(function () {
var R = /*__RECIPE__*/null;

var scriptFolder = File($.fileName).parent;
var assets = new Folder(scriptFolder.fsName + "/assets");
if (!assets.exists) { alert("Cannot find the 'assets' folder next to this script:\n" + assets.fsName); return; }

app.beginUndoGroup("Build RackNap Easy – Catalog & Marketplace");
var proj = app.project || app.newProject();
var root = proj.items.addFolder("RackNap Easy – Catalog & Marketplace");
var fAssets = proj.items.addFolder("Assets"); fAssets.parentFolder = root;
var fComps = proj.items.addFolder("Precomps"); fComps.parentFolder = root;

var footage = {};
function importAsset(name) {
    if (footage[name]) return footage[name];
    var f = new File(assets.fsName + "/" + name);
    if (!f.exists) throw new Error("Missing asset: " + f.fsName);
    var item = proj.importFile(new ImportOptions(f));
    item.parentFolder = fAssets;
    footage[name] = item;
    return item;
}
function rgb(c) { return [c[0] / 255, c[1] / 255, c[2] / 255]; }

var TR = { anchorPoint: "ADBE Anchor Point", position: "ADBE Position", scale: "ADBE Scale", opacity: "ADBE Opacity",
           xRotation: "ADBE Rotate X", yRotation: "ADBE Rotate Y", zRotation: "ADBE Rotate Z" };
function tprop(layer, key) { return layer.property("ADBE Transform Group").property(TR[key]); }

function isSpatial(p) {
    return p.propertyValueType === PropertyValueType.TwoD_SPATIAL || p.propertyValueType === PropertyValueType.ThreeD_SPATIAL;
}
function clampInf(v) { return Math.max(0.1, Math.min(100, v)); }
function arr(v) { return (v instanceof Array) ? v : [v]; }

/* Sets keyframes. Each key: {t, v, e, inT?, outT?}; e is the easing of the
   segment that starts at this key: a name in R.ease (cubic-bezier), "hold" or "linear". */
/* match a value to the property's dimensions (2D layers report 3-value scale/position in some versions) */
function fit(p, v) {
    var cur = p.value;
    if (!(cur instanceof Array)) return (v instanceof Array) ? v[0] : v;
    var o = [], j, src = arr(v);
    for (j = 0; j < cur.length; j++) o.push(j < src.length ? src[j] : (p.matchName === "ADBE Scale" ? src[0] : 0));
    return o;
}
function applyKeys(p, ks) {
    var i, d, n = ks.length, idx = [];
    for (i = 0; i < n; i++) ks[i].v = fit(p, ks[i].v);
    for (i = 0; i < n; i++) p.setValueAtTime(ks[i].t, ks[i].v);
    for (i = 0; i < n; i++) idx.push(p.nearestKeyIndex(ks[i].t));
    var spatial = isSpatial(p);
    var dims = arr(ks[0].v).length, ne = spatial ? 1 : dims;
    var BZ = KeyframeInterpolationType.BEZIER, HOLD = KeyframeInterpolationType.HOLD, LIN = KeyframeInterpolationType.LINEAR;
    for (i = 0; i < n; i++) {
        var inType = (i > 0) ? (ks[i - 1].e === "hold" ? HOLD : (ks[i - 1].e === "linear" ? LIN : BZ)) : BZ;
        var outType = (i < n - 1) ? (ks[i].e === "hold" ? HOLD : (ks[i].e === "linear" ? LIN : BZ)) : BZ;
        p.setInterpolationTypeAtKey(idx[i], inType, outType);
    }
    // temporal ease from cubic-bezier
    var inE = [], outE = [];
    for (i = 0; i < n; i++) { inE.push([]); outE.push([]); for (d = 0; d < ne; d++) { inE[i].push(new KeyframeEase(0, 16.67)); outE[i].push(new KeyframeEase(0, 16.67)); } }
    for (i = 0; i < n - 1; i++) {
        var e = ks[i].e; if (!R.ease[e]) continue;
        var bz = R.ease[e], dt = ks[i + 1].t - ks[i].t; if (dt <= 0) continue;
        var a = arr(ks[i].v), b = arr(ks[i + 1].v);
        for (d = 0; d < ne; d++) {
            var dv;
            if (spatial) { var s = 0, k; for (k = 0; k < a.length; k++) s += (b[k] - a[k]) * (b[k] - a[k]); dv = Math.sqrt(s); }
            else dv = b[d] - a[d];
            outE[i][d] = new KeyframeEase(bz[1] / bz[0] * dv / dt, clampInf(bz[0] * 100));
            inE[i + 1][d] = new KeyframeEase((1 - bz[3]) / (1 - bz[2]) * dv / dt, clampInf((1 - bz[2]) * 100));
        }
    }
    for (i = 0; i < n; i++) {
        var bzIn = (i > 0) && (R.ease[ks[i - 1].e] !== undefined), bzOut = (i < n - 1) && (R.ease[ks[i].e] !== undefined);
        if (!bzIn && !bzOut) continue; // linear/hold on both sides: leave AE's interpolation alone
        try { p.setTemporalEaseAtKey(idx[i], inE[i], outE[i]); } catch (err) {}
    }
    if (spatial) {
        for (i = 0; i < n; i++) {
            var z = []; for (d = 0; d < dims; d++) z.push(0);
            p.setSpatialAutoBezierAtKey(idx[i], false);
            p.setSpatialContinuousAtKey(idx[i], false);
            p.setSpatialTangentsAtKey(idx[i], pad(ks[i].inT, dims), pad(ks[i].outT, dims));
        }
    }
    function pad(t, dims) { var o = [], j; for (j = 0; j < dims; j++) o.push(t && t[j] !== undefined ? t[j] : 0); return o; }
}

function addEffects(layer, effects) {
    if (!effects) return;
    var parade = layer.property("ADBE Effect Parade"), i, k;
    for (i = 0; i < effects.length; i++) {
        var ef = effects[i], fx = parade.addProperty(ef.match);
        if (ef.name) fx.name = ef.name;
        if (ef.props) for (k in ef.props) if (ef.props.hasOwnProperty(k)) fx.property(k).setValue(ef.props[k]);
        ef._fx = fx;
    }
}
function keyEffects(effects) {
    if (!effects) return;
    var i, k;
    for (i = 0; i < effects.length; i++) if (effects[i].keys)
        for (k in effects[i].keys) if (effects[i].keys.hasOwnProperty(k)) applyKeys(effects[i]._fx.property(k), effects[i].keys[k]);
}

function makeText(comp, spec) {
    var lyr = comp.layers.addText(spec.text.string);
    var sp = lyr.property("ADBE Text Properties").property("ADBE Text Document");
    var td = sp.value;
    try { td.resetCharStyle(); td.resetParagraphStyle(); } catch (e) {}
    td.font = spec.text.font;
    td.fontSize = spec.text.size;
    td.applyFill = true; td.fillColor = rgb(spec.text.color);
    td.applyStroke = false;
    td.tracking = spec.text.tracking;
    td.justification = ParagraphJustification.LEFT_JUSTIFY;
    sp.setValue(td);
    return lyr;
}

var built = {};
function buildComp(c) {
    var comp = proj.items.addComp(c.name, c.w, c.h, 1, R.dur, R.fps);
    comp.parentFolder = c.open ? root : fComps;
    comp.bgColor = rgb(c.bg);
    comp.motionBlur = true;
    try { comp.shutterAngle = 180; comp.shutterPhase = -90; } catch (e) {}
    var byName = {}, specs = c.layers, i, s, lyr;
    // 1) create layers bottom -> top with static values
    for (i = 0; i < specs.length; i++) {
        s = specs[i];
        if (s.type === "image" || s.type === "audio") lyr = comp.layers.add(importAsset(s.file));
        else if (s.type === "comp") lyr = comp.layers.add(built[s.comp]);
        else if (s.type === "null") { lyr = comp.layers.addNull(R.dur); }
        else if (s.type === "solid") lyr = comp.layers.addSolid(rgb(s.color), s.name, s.w, s.h, 1, R.dur);
        else if (s.type === "adjustment") { lyr = comp.layers.addSolid([1, 1, 1], s.name, c.w, c.h, 1, R.dur); lyr.adjustmentLayer = true; }
        else if (s.type === "text") lyr = makeText(comp, s);
        else if (s.type === "camera") {
            lyr = comp.layers.addCamera(s.name, s.center);
            lyr.property("ADBE Camera Options Group").property("ADBE Camera Zoom").setValue(s.zoom);
            tprop(lyr, "position").setValue([s.center[0], s.center[1], -s.zoom]);
            tprop(lyr, "anchorPoint").setValue([s.center[0], s.center[1], 0]);
        }
        lyr.name = s.name;
        if (s.comment) lyr.comment = s.comment;
        if (s.threeD) lyr.threeDLayer = true;
        if (s.collapse) { try { lyr.collapseTransformation = true; } catch (e) {} }
        if (s.motionBlur) { try { lyr.motionBlur = true; } catch (e) {} }
        if (s.guide) lyr.guideLayer = true;
        if (s.type !== "camera" && s.type !== "audio" && !R.localParenting) {
            if (s.anchor) { var pp = tprop(lyr, "anchorPoint"); pp.setValue(fit(pp, s.anchor)); }
            if (s.position) { var pp = tprop(lyr, "position"); pp.setValue(fit(pp, s.position)); }
            if (s.fitWidth) { var k = s.fitWidth / lyr.source.width * 100; var ps = tprop(lyr, "scale"); ps.setValue(fit(ps, [k, k])); }
            if (s.opacity !== undefined) tprop(lyr, "opacity").setValue(s.opacity);
        }
        if (s.inPoint !== undefined) lyr.inPoint = s.inPoint;
        if (s.outPoint !== undefined) lyr.outPoint = s.outPoint;
        addEffects(lyr, s.effects);
        s._layer = lyr; byName[s.name] = lyr;
    }
    // 2) parenting (before any keyframes so nothing jumps)
    if (R.localParenting) {
        // parents start at an identity transform so children keep their values,
        // then every static value is set in its parent's space
        for (i = 0; i < specs.length; i++) if (specs[i].parent) {
            var pl = byName[specs[i].parent];
            tprop(pl, "anchorPoint").setValue(fit(tprop(pl, "anchorPoint"), [0, 0, 0]));
            tprop(pl, "position").setValue(fit(tprop(pl, "position"), [0, 0, 0]));
            tprop(pl, "scale").setValue(fit(tprop(pl, "scale"), [100, 100, 100]));
        }
        for (i = 0; i < specs.length; i++) if (specs[i].parent) specs[i]._layer.parent = byName[specs[i].parent];
        for (i = 0; i < specs.length; i++) {
            s = specs[i]; lyr = s._layer;
            if (s.type === "camera" || s.type === "audio") continue;
            if (s.anchor) { var pa = tprop(lyr, "anchorPoint"); pa.setValue(fit(pa, s.anchor)); }
            if (s.position) { var pq = tprop(lyr, "position"); pq.setValue(fit(pq, s.position)); }
            if (s.fitWidth) { var kk = s.fitWidth / lyr.source.width * 100; var pz = tprop(lyr, "scale"); pz.setValue(fit(pz, [kk, kk])); }
            if (s.opacity !== undefined) tprop(lyr, "opacity").setValue(s.opacity);
        }
    } else {
        for (i = 0; i < specs.length; i++) if (specs[i].parent) specs[i]._layer.parent = byName[specs[i].parent];
    }
    // 3) keyframes
    for (i = 0; i < specs.length; i++) {
        s = specs[i];
        if (s.keys) for (var key in s.keys) if (s.keys.hasOwnProperty(key)) applyKeys(tprop(s._layer, key), s.keys[key]);
        keyEffects(s.effects);
    }
    // 4) expressions
    for (i = 0; i < specs.length; i++) {
        s = specs[i];
        if (s.expressions) for (var ek in s.expressions) if (s.expressions.hasOwnProperty(ek)) tprop(s._layer, ek).expression = s.expressions[ek];
    }
    // 4b) text expressions (e.g. count-up numbers)
    for (i = 0; i < specs.length; i++) {
        s = specs[i];
        if (s.textExpression) s._layer.property("ADBE Text Properties").property("ADBE Text Document").expression = s.textExpression;
    }
    // 5) track mattes (matte sits directly above its text layer)
    for (i = 0; i < specs.length; i++) {
        s = specs[i]; if (!s.matte) continue;
        var m = byName[s.matte], t = s._layer;
        if (typeof t.setTrackMatte === "function") t.setTrackMatte(m, TrackMatteType.ALPHA);
        else t.trackMatteType = TrackMatteType.ALPHA;
        m.enabled = false;
    }
    built[c.id] = comp;
    return comp;
}

var mainComp = null;
try {
    for (var ci = 0; ci < R.comps.length; ci++) {
        var comp = buildComp(R.comps[ci]);
        if (R.comps[ci].open) mainComp = comp;
    }
} catch (err) {
    alert("Build stopped: " + err.toString() + (err.line ? " (line " + err.line + ")" : ""));
}
app.endUndoGroup();
if (mainComp) {
    mainComp.openInViewer();
    mainComp.time = 13.9;
}
})();
